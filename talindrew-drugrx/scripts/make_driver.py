"""Write a tiny driver that runs a script with fixed arguments on the VM.

`colab exec -f foo.py` sends a local file to the kernel but **forwards no
arguments** — only `colab run` does that, and `colab run` provisions a fresh VM
and tears it down afterwards, which is the wrong shape for a long training run
we mean to resume.

So the arguments are baked into a generated driver, which is what gets sent.
The driver also puts `/content` on `sys.path` and avoids `SystemExit`, because
raising it inside the IPython kernel prints a traceback that looks like a
failure in the logs even when the run succeeded.

    python scripts/make_driver.py train_admet.py --epochs 100 --lr 3e-4
    colab exec -s drugrx-l4 -f /tmp/drugrx_driver.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

TEMPLATE = '''\
# generated by scripts/make_driver.py — do not edit
import runpy, sys, os, traceback

sys.path.insert(0, "/content")
os.chdir("/content")

sys.argv = {argv!r}
print("[driver] running {script} with", " ".join(sys.argv[1:]), flush=True)

try:
    runpy.run_path("/content/scripts/{script}", run_name="__main__")
except SystemExit as exc:
    # A clean exit is not a failure; only a non-zero code is.
    code = exc.code if isinstance(exc.code, int) else (0 if exc.code is None else 1)
    print(f"[driver] exited with code {{code}}", flush=True)
    if code:
        raise
except Exception:
    traceback.print_exc()
    raise
'''


DETACHED = '''\
# generated by scripts/make_driver.py --detach — do not edit
import subprocess, sys, os

os.makedirs("/content/runs", exist_ok=True)
log = "{log}"
cmd = [sys.executable, "/content/scripts/{script}"] + {args!r}

# start_new_session detaches the child from this kernel's process group, so the
# job outlives the `colab exec` call. Without it, a client timeout or a kernel
# interrupt takes a 20-hour run down with it.
with open(log, "ab", buffering=0) as fh:
    proc = subprocess.Popen(
        cmd, stdout=fh, stderr=subprocess.STDOUT,
        cwd="/content", start_new_session=True,
        env={{**os.environ, "PYTHONPATH": "/content", "PYTHONUNBUFFERED": "1"}},
    )
print(f"[driver] detached pid {{proc.pid}}, logging to {{log}}", flush=True)
'''


def main() -> int:
    argv = sys.argv[1:]
    detach = False
    log = "/content/runs/train.log"
    if "--detach" in argv:
        detach = True
        argv.remove("--detach")
    if "--log" in argv:
        i = argv.index("--log")
        log = argv[i + 1]
        del argv[i:i + 2]

    if not argv:
        print(__doc__)
        return 1
    script = argv[0]
    args = argv[1:]
    out = Path("/tmp/drugrx_driver.py")
    if detach:
        out.write_text(DETACHED.format(script=script, args=args, log=log))
    else:
        out.write_text(TEMPLATE.format(argv=[script, *args], script=script))
    print(f"wrote {out}")
    print(json.dumps({"script": script, "args": args}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
