"""Build the servable router bundle: 21 boosters, the ensemble, and the domain pack.

**19 of 21 endpoints currently have no servable model at all.** `ROUTING.md` sends
them to gradient boosting, and `baseline.py` fits a booster, scores it and throws
it away — so "the registry dispatches per endpoint" was, until this script, a plan
to dispatch to something that did not exist. `ship_artifact.py` saves the ensemble,
which serves the one or two endpoints that earned it.

What the bundle carries, and why each piece is in it rather than in code:

* **`routing.json`** — which model serves which endpoint, with the effect size and
  interval behind the decision. Generated by `route_select.py`, copied here
  verbatim. A dispatch decision cannot have prose as its source of truth.
* **`gbm/<endpoint>.txt`** — LightGBM's own text format, not a pickle. A pickle ties
  the serving container to the exact scikit-learn that fitted it; a booster text
  file loads in any LightGBM.
* **`gbm/meta.json`** — per endpoint: the arm (which decides the featuriser), the
  task type, the metric, and the committed score the booster must reproduce.
* **`domain/*.npz`** — packed training fingerprints and the **background-calibrated**
  in-domain threshold per endpoint (`drugrx/domain.py`). This is what turns a
  prediction into a prediction with a stated applicability domain, and it is per
  endpoint because the background moves with the reference set's size and breadth.
* **`ensemble.pt`** — the neural checkpoint, unchanged, for the endpoints routed to it.
* **`card.md`** — the caveats, which travel with the numbers or they are not caveats.

**Acceptance is reproduction, not a smoke test.** Every booster is reloaded from the
text file it was just written to, re-predicts its own test fold, and must match the
score computed at fit time to 1e-6. An artifact that cannot reproduce the number on
its own card is not the model that was measured.

    python scripts/ship_router.py --arms runs/routing/arms.json \\
        --routing runs/routing/routing.json --ensemble /content/artifact/ensemble.pt
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, "/content")
sys.path.insert(0, str(Path(__file__).resolve().parent))

from drugrx.data.standardise import standardise_many  # noqa: E402
from drugrx.data.tdc import ADMET_TASKS, AdmetTask, load_task  # noqa: E402
from drugrx.domain import background_excluding, build_reference  # noqa: E402

#: Our endpoint keys mapped to the names admet-ai already uses, so the two ADMET
#: models speak one vocabulary and the existing panel renders both. A user who
#: switches model should see the same rows, not a different dictionary.
TDC_NAMES: dict[str, str] = {
    "caco2": "Caco2_Wang",
    "bioavailability": "Bioavailability_Ma",
    "lipophilicity": "Lipophilicity_AstraZeneca",
    "solubility": "Solubility_AqSolDB",
    "hia": "HIA_Hou",
    "pgp": "Pgp_Broccatelli",
    "bbb": "BBB_Martins",
    "ppbr": "PPBR_AZ",
    "vdss": "VDss_Lombardo",
    "cyp2c9_inhib": "CYP2C9_Veith",
    "cyp2d6_inhib": "CYP2D6_Veith",
    "cyp3a4_inhib": "CYP3A4_Veith",
    "cyp2c9_sub": "CYP2C9_Substrate_CarbonMangels",
    "cyp2d6_sub": "CYP2D6_Substrate_CarbonMangels",
    "cyp3a4_sub": "CYP3A4_Substrate_CarbonMangels",
    "half_life": "Half_Life_Obach",
    "cl_micro": "Clearance_Microsome_AZ",
    "ld50": "LD50_Zhu",
    "herg": "hERG",
    "ames": "AMES",
    "dili": "DILI",
}

#: The ExpansionRx auxiliary heads, in their **own** namespace. `ExpansionRx_CLint`
#: and `Clearance_Microsome_AZ` are different measurements from different labs whose
#: panels share **zero** molecules, so no cross-lab offset is even estimable. The
#: names exist to make comparing them obviously wrong rather than merely discouraged.
ERX_PREFIX = "ExpansionRx_"


def score(task: AdmetTask, y_true: np.ndarray, y_pred: np.ndarray) -> float:
    from scipy.stats import spearmanr
    from sklearn.metrics import average_precision_score, mean_absolute_error, roc_auc_score

    if task.metric == "mae":
        return float(mean_absolute_error(y_true, y_pred))
    if task.metric == "spearman":
        return float(spearmanr(y_true, y_pred).statistic)
    if task.metric == "pr_auc":
        return float(average_precision_score(y_true, y_pred))
    return float(roc_auc_score(y_true, y_pred))


def fit_booster(task: AdmetTask, xtr, ytr, xva, yva, seed: int):
    """`baseline.py`'s LightGBM, returned rather than discarded.

    Hyper-parameters identical to the committed baseline: this script ships the
    measured model, so the learner must not move. `random_state` is set because a
    served model has to be the same model twice.
    """
    import lightgbm as lgb

    common = dict(
        n_estimators=2000, learning_rate=0.05, num_leaves=31, min_child_samples=10,
        colsample_bytree=0.6, subsample=0.8, subsample_freq=1, reg_lambda=1.0,
        verbose=-1, n_jobs=-1, random_state=seed,
    )
    model = lgb.LGBMClassifier(**common) if task.task == "binary" else lgb.LGBMRegressor(**common)
    model.fit(xtr, ytr, eval_set=[(xva, yva)],
              eval_metric="auc" if task.task == "binary" else "l1",
              callbacks=[lgb.early_stopping(100, verbose=False)])
    return model.booster_


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--arms", required=True, help="route_select.py's arms.json")
    ap.add_argument("--routing", default="", help="route_select.py's routing.json")
    ap.add_argument("--ensemble", default="", help="ensemble.pt to include")
    ap.add_argument("--out", default="/content/router")
    ap.add_argument("--cache", default="data/featcache")
    ap.add_argument("--workers", type=int, default=None)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--background", type=int, default=2000,
                    help="molecules sampled from other endpoints as the domain background")
    ap.add_argument("--repo", default="arnab2812/drugrx-admet-router")
    ap.add_argument("--push", action="store_true")
    ap.add_argument("--domain-only", action="store_true",
                    help="rebuild only the applicability-domain pack, reusing the "
                         "boosters already in --out. The calibration changed once "
                         "after the boosters were correct, and refitting 21 models "
                         "to recompute a threshold would be 20 minutes spent proving "
                         "nothing.")
    args = ap.parse_args()

    from baseline import featurise_arm

    arms = {r["task"]: r for r in json.loads(Path(args.arms).read_text())["results"]}
    out = Path(args.out)
    (out / "gbm").mkdir(parents=True, exist_ok=True)
    (out / "domain").mkdir(parents=True, exist_ok=True)

    # The domain background is ordinary drug-like chemistry that is **not in this
    # endpoint's training set**, and the exclusion is the load-bearing part.
    #
    # Pooling molecules from the other endpoints is the cheap way to get a
    # background, but TDC's datasets overlap heavily — the same approved drugs
    # appear in a dozen of them. Without the exclusion, a sizeable share of an
    # endpoint's "background" would be its own training molecules, each scoring a
    # nearest neighbour of 1.0 against itself. That inflates the background, which
    # raises the threshold, which makes genuinely in-domain queries read as
    # out-of-domain: a calibration that quietly measures dataset overlap instead of
    # chemistry.
    #
    # **Excluded on standardised InChIKey, not on the SMILES string.** A string
    # join is what matched 21 of lipophilicity's 420 molecules and reported it as
    # clean; here it would leave every salt form and re-spelled tautomer of a
    # training molecule sitting in its own background.
    pool: dict[str, list[str]] = {}
    for task in ADMET_TASKS:
        frame, _ = load_task(task)
        pool[task.key] = frame["smiles"].tolist()

    print("\n[router] standardising the molecule pool for the domain background",
          flush=True)
    every = sorted({s for items in pool.values() for s in items})
    results = standardise_many(every, workers=args.workers)
    key_of = {smi: (r.inchikey if r.ok else f"__raw__{smi}")
              for smi, r in zip(every, results)}
    failed = sum(1 for r in results if not r.ok)
    print(f"[router] {len(every)} unique SMILES, {failed} unstandardisable "
          f"({failed / max(len(every), 1):.1%})", flush=True)

    rng = np.random.default_rng(args.seed)
    existing: dict[str, dict] = {}
    meta_file = out / "gbm" / "meta.json"
    if args.domain_only:
        if not meta_file.exists():
            raise SystemExit(f"--domain-only needs an existing {meta_file}")
        existing = json.loads(meta_file.read_text())["endpoints"]
    gbm_meta: dict[str, dict] = {}
    reproduce: list[dict] = []

    for task in ADMET_TASKS:
        row = arms.get(task.key)
        if row is None:
            print(f"  {task.key}: not in arms.json, skipped")
            continue
        arm = row["chosen"]
        print(f"\n── {task.key} [{arm}] ──────────", flush=True)

        frame, splits = load_task(task)
        smiles = frame["smiles"].tolist()
        y = frame["y"].to_numpy(dtype=float)
        if not (splits and all(k in splits for k in ("train", "valid", "test"))):
            print("  no official split; skipped")
            continue
        tr, va, te = (np.array(splits[k]) for k in ("train", "valid", "test"))

        if args.domain_only:
            fitted = float(existing.get(task.key, {}).get("test_score", float("nan")))
        else:
            x = featurise_arm(smiles, arm, Path(args.cache), args.workers)
            booster = fit_booster(task, x[tr], y[tr], x[va], y[va], args.seed)
            pred = booster.predict(x[te])
            fitted = score(task, y[te], np.asarray(pred))

            path = out / "gbm" / f"{task.key}.txt"
            booster.save_model(str(path))

            # ── acceptance: the file must be the model ────────────────────
            import lightgbm as lgb

            reloaded = lgb.Booster(model_file=str(path))
            again = score(task, y[te], np.asarray(reloaded.predict(x[te])))
            if abs(again - fitted) > 1e-6:
                raise SystemExit(
                    f"{task.key}: reloaded booster scores {again:.6f} but the fitted "
                    f"one scored {fitted:.6f} — the saved file is not the model that "
                    "was measured"
                )
            reproduce.append({"task": task.key, "fitted": fitted, "reloaded": again})
            print(f"  test {task.metric}={fitted:.4f}  reload OK  "
                  f"({path.stat().st_size / 1e6:.1f} MB)", flush=True)

        # ── the applicability domain for this endpoint ────────────────────
        train_smiles = [smiles[i] for i in tr]
        others = background_excluding(
            [s for k, v in pool.items() if k != task.key for s in v],
            train_smiles, key_of,
        )
        if len(others) < 200:
            raise SystemExit(
                f"{task.key}: only {len(others)} background molecules survive the "
                "training-set exclusion; the threshold would not be calibratable"
            )
        background = rng.choice(np.array(others, dtype=object),
                                size=min(args.background, len(others)),
                                replace=False).tolist()
        # Calibrated on the **validation** fold, never on test: the threshold is a
        # property of a fold we do not report scores on, which leaves the test
        # fold's in-domain rate an honest measurement rather than a definition.
        ref = build_reference(task.key, train_smiles, background,
                              [smiles[i] for i in va])
        np.savez_compressed(out / "domain" / f"{task.key}.npz", **ref.to_npz())
        print(f"  domain: {ref.n_reference} reference, threshold {ref.threshold:.3f} "
              f"(q{ref.quantile:.0f} of {ref.calibration_n} validation molecules, "
              f"median {ref.calibration_median:.3f}; random background median "
              f"{ref.background_median:.3f})", flush=True)

        gbm_meta[task.key] = {
            "arm": arm,
            "name": TDC_NAMES[task.key],
            "task": task.task,
            "metric": task.metric,
            "meaning": task.meaning,
            "test_score": fitted,
            "n_train": int(len(tr)),
            "n_test": int(len(te)),
            "domain_threshold": ref.threshold,
            "domain_quantile": ref.quantile,
            "domain_calibration_n": ref.calibration_n,
            "domain_calibration_median": ref.calibration_median,
            "domain_background_median": ref.background_median,
            "domain_reference_n": ref.n_reference,
        }

    (out / "gbm" / "meta.json").write_text(json.dumps(
        {"generated": time.strftime("%Y-%m-%dT%H:%M:%S"), "seed": args.seed,
         "endpoints": gbm_meta}, indent=2, default=float))
    if reproduce:
        (out / "reproduce.json").write_text(json.dumps(
            {"generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
             "tolerance": 1e-6, "rows": reproduce}, indent=2, default=float))
    elif args.domain_only:
        # The boosters were not touched, so the reproduction record still stands
        # and must not be overwritten with an empty one.
        print("[router] --domain-only: reproduce.json left as it was", flush=True)

    if args.routing:
        shutil.copy(args.routing, out / "routing.json")
    if args.ensemble:
        shutil.copy(args.ensemble, out / "ensemble.pt")

    print(f"\n[router] {len(gbm_meta)} boosters, {len(gbm_meta)} domain references → {out}")

    if args.push:
        import os

        from huggingface_hub import HfApi

        token = os.environ.get("HF_TOKEN", "")
        if not token:
            print("[router] HF_TOKEN unset; not pushing")
            return 1
        api = HfApi(token=token)
        api.create_repo(args.repo, repo_type="model", private=True, exist_ok=True)
        api.upload_folder(folder_path=str(out), repo_id=args.repo, repo_type="model")
        print(f"[router] pushed to {args.repo}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
