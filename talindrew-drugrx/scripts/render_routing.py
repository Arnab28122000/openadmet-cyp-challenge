"""Render `runs/ROUTING.md` from the machine-readable table, so the two cannot drift.

`routing.json` is the source of truth — a dispatch decision cannot have prose
behind it — and this writes the human version from it. Running it is the only
sanctioned way to change `ROUTING.md`: a hand-edit would produce a document that
disagrees with what the router actually does, which is worse than no document.

Local on purpose. `route_select.py` runs on a disposable VM and `docs/` is not
its to write.

    python scripts/render_routing.py --routing runs/routing/routing.json \\
        --arms runs/routing/arms.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT.parent / "docs" / "drugrx-training" / "runs"

HEADER = """# Routing table — decided by effect size, not by win count

**Generated by `scripts/render_routing.py` from `runs/routing/routing.json`. Do not hand-edit:**
the JSON is what the served router dispatches on, and a document that disagrees with it is worse
than no document.

An endpoint routes to the neural ensemble **only when its 95% confidence interval excludes zero in
the ensemble's favour**. Everything else routes to gradient boosting: it is cheaper, needs no GPU,
and its failure modes are better understood. An **undecided** endpoint goes to gradient boosting —
"we could not tell" must never resolve to the more expensive model by omission.

Two things this version fixes about the first one, both of which could have changed a verdict:

* **The gradient-boosting arm is chosen per endpoint, on the validation fold.** The first table
  compared the ensemble against `count-rdkit2d` alone, while H5 had already shown `maplight`
  (+Avalon +ErG) better on 14 of 21 endpoints — so it was not comparing against the model we would
  actually serve. Choosing the arm on *test* would have been test-set selection and would have
  inflated gradient boosting by construction, so the arm is picked on the official validation fold
  by models early-stopped on an **inner** split of train.
* **The interval covers the booster's own seed variance.** `baseline.py` subsamples rows and columns
  and set no `random_state`: two runs of the same arm disagree by up to 0.094, and on 9 of 21
  endpoints that spread is as large as the arm effect. The first table's bootstrap resampled
  molecules while holding one fit fixed, so its intervals were too narrow — most visibly on `pgp`,
  whose lower bound was +0.0017 against a same-arm spread of ±0.0083. Here each bootstrap draw takes
  a fresh GBM fit **and** a molecule resample.

**What the interval does not cover, stated so it is not mistaken for coverage.** The ensemble side is
one specific checkpoint — the artifact actually served — so its own initialisation variance is not in
the interval. That is the right choice for the question being asked ("is *this* checkpoint better than
*that arm*"), and the wrong one for a question nobody here is asking ("is the ensemble *method* better
than the gradient-boosting *method*"). Re-ship the artifact and this table must be rebuilt.
"""

FOOTER = """
## A low score here does not mean a hard assay

The table invites an inference it does not support: that an endpoint we predict badly is one whose
chemistry is hard. It may instead be one whose *labels* are noisy, and the two call for opposite
responses — better representation in the first case, more or cleaner data in the second.

There is a concrete counterexample from this programme's own CYP-challenge track, where the shipped
per-compound `_std` columns allow assay reproducibility to be measured directly: **the endpoint ranking
came out nearly inverted against the model scores.** The noisiest endpoint there (CYP3A4, ~10.2% of
variance) is the one predicted best; the second cleanest (CYP2D6, ~6.7%) is predicted worst.

**That measurement does not transfer to this table.** None of TDC's 21 endpoints ships a replicate
spread, so no noise ceiling is available for any row here, and any figure quoted for one would be
invented. It is recorded only as a reason not to read a low number as a statement about the chemistry.
A further limit holds even where `_std` does exist: it measures **assay reproducibility**, not the
irreducible error of predicting a *new* molecule, and those differ by however much chemistry the split
withholds — which is the gap this programme spends most of its time measuring.

Caveats that travel with every number here: the test folds are TDC's official splits, and test
molecules sit measurably closer to their training set than to ordinary chemistry on 20 of 21
endpoints (background-calibrated shift +0.019 to +0.180, `runs/leakage_calibrated.json`), so
absolute values are optimistic for new chemistry. The comparison between the two columns is sound;
the absolute level is not.
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--routing", default=str(DOCS / "routing" / "routing.json"))
    ap.add_argument("--arms", default=str(DOCS / "routing" / "arms.json"))
    ap.add_argument("--out", default=str(DOCS / "ROUTING.md"))
    args = ap.parse_args()

    routing = json.loads(Path(args.routing).read_text())
    arms = {r["task"]: r for r in json.loads(Path(args.arms).read_text())["results"]}

    rows = sorted(routing["rows"], key=lambda r: r.get("diff", 0.0), reverse=True)
    ensemble = [r["task"] for r in rows if r["serves"] == "ensemble"]

    lines = [HEADER, ""]
    lines.append(f"Generated {routing['generated']} from {routing['seeds']} fits per arm.")
    lines.append("")
    lines.append("| endpoint | serves | GBM arm | n | diff | 95% CI | verdict |")
    lines.append("|---|---|---|---|---|---|---|")
    for r in rows:
        if "diff" not in r:
            lines.append(
                f"| {r['task']} | {r['serves']} | {r.get('arm', '—')} | "
                f"{r.get('n_shared', 0)} | — | — | undecided ({r.get('reason', '')}) |"
            )
            continue
        mark = "**" if r["verdict"] != "undecided" else ""
        lines.append(
            f"| {r['task']} | {r['serves']} | {r['arm']} | {r['n_shared']} | "
            f"{r['diff']:+.4f} | [{r['ci_low']:+.4f}, {r['ci_high']:+.4f}] | "
            f"{mark}{r['verdict']}{mark} |"
        )

    lines.append("")
    lines.append(
        f"**Ensemble serves {len(ensemble)} endpoint"
        f"{'' if len(ensemble) == 1 else 's'}"
        f"{': ' + ', '.join(ensemble) if ensemble else ' — none'}. "
        f"Gradient boosting serves the other {len(rows) - len(ensemble)}.**"
    )

    # The arm selection, shown rather than asserted: a reader who doubts a choice
    # should be able to see the validation scores it was made on.
    lines.append("")
    lines.append("## Which gradient-boosting arm, and on what")
    lines.append("")
    lines.append("Chosen on the official **validation** fold, never on test.")
    lines.append("")
    lines.append("| endpoint | chosen | count-rdkit2d (valid) | maplight (valid) | inside the spread? |")
    lines.append("|---|---|---|---|---|")
    for r in rows:
        a = arms.get(r["task"])
        if a is None:
            continue
        mean, std = a["valid_mean"], a["valid_std"]
        lines.append(
            f"| {r['task']} | {a['chosen']} | "
            f"{mean['count-rdkit2d']:.4f} ± {std['count-rdkit2d']:.4f} | "
            f"{mean['maplight']:.4f} ± {std['maplight']:.4f} | "
            f"{'**yes**' if a.get('within_noise') else 'no'} |"
        )

    lines.append(FOOTER)
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")
    print(f"ensemble serves {len(ensemble)}: {', '.join(ensemble) or '(none)'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
